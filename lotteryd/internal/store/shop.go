const shopSchemaSQL = `
CREATE TABLE IF NOT EXISTS points_assets (
 id TEXT PRIMARY KEY, kind TEXT NOT NULL, mime TEXT NOT NULL, data BYTEA NOT NULL,
 created_by BIGINT NOT NULL, created_at TEXT NOT NULL
);
ALTER TABLE items ADD COLUMN IF NOT EXISTS cover_asset TEXT NOT NULL DEFAULT '';
ALTER TABLE items ADD COLUMN IF NOT EXISTS active_asset TEXT NOT NULL DEFAULT '';
ALTER TABLE items ADD COLUMN IF NOT EXISTS expired_asset TEXT NOT NULL DEFAULT '';
ALTER TABLE items ADD COLUMN IF NOT EXISTS animation_asset TEXT NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS points_shop_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind TEXT NOT NULL CHECK (kind IN ('item','custom')),
 item_id BIGINT REFERENCES items(id), icon_asset TEXT NOT NULL DEFAULT '',
 name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 price BIGINT NOT NULL CHECK (price BETWEEN 1 AND 1000000000000),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
 sort_order INTEGER NOT NULL DEFAULT 0,
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
 CHECK ((kind='item' AND item_id IS NOT NULL) OR (kind='custom' AND item_id IS NULL))
);
`

type PointsAsset struct {
	ID, Kind, MIME string
	Data           []byte
}

func (s *Store) SavePointsAsset(asset PointsAsset, adminID int64) error {
	_, err := s.db.Exec(`INSERT INTO points_assets (id,kind,mime,data,created_by,created_at) VALUES ($1,$2,$3,$4,$5,$6) ON CONFLICT DO NOTHING`,
		asset.ID, asset.Kind, asset.MIME, asset.Data, adminID, fmtTime(time.Now()))
	return err
}

func (s *Store) GetPointsAsset(id string) (PointsAsset, error) {
	var asset PointsAsset
	err := s.db.QueryRow(`SELECT id,kind,mime,data FROM points_assets WHERE id=$1`, id).Scan(&asset.ID, &asset.Kind, &asset.MIME, &asset.Data)
	return asset, err
}

type ManagedItem struct {
	ID             int64        `json:"id"`
	Code           string       `json:"code"`
	Name           string       `json:"name"`
	Description    string       `json:"description"`
	CoverAsset     string       `json:"cover_asset"`
	ActiveAsset    string       `json:"active_asset"`
	ExpiredAsset   string       `json:"expired_asset"`
	AnimationAsset string       `json:"animation_asset"`
	Effect         *EventAction `json:"effect,omitempty"`
}

const managedItemColumns = `id,code,name,description,cover_asset,active_asset,expired_asset,animation_asset,kind,params_json`

func (s *Store) ListManagedItems() ([]ManagedItem, error) {
	rows, err := s.db.Query(`SELECT ` + managedItemColumns + ` FROM items ORDER BY id DESC`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	items := make([]ManagedItem, 0)
	for rows.Next() {
		var it ManagedItem
		var kind, params string
		if err := rows.Scan(&it.ID, &it.Code, &it.Name, &it.Description, &it.CoverAsset, &it.ActiveAsset, &it.ExpiredAsset, &it.AnimationAsset, &kind, &params); err != nil {
			return nil, err
		}
		if kind == "grant_points" || kind == "grant_item" {
			var effect EventAction
			if err := json.Unmarshal([]byte(params), &effect); err != nil {
				return nil, err
			}
			effect.Kind = kind
			it.Effect = &effect
		}
		items = append(items, it)
	}
	return items, rows.Err()
}

var ErrInvalidShopData = errors.New("invalid item or product data")

func requireAsset(tx *sql.Tx, id string, kinds ...string) error {
	var kind string
	if err := tx.QueryRow(`SELECT kind FROM points_assets WHERE id=$1`, id).Scan(&kind); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return ErrInvalidShopData
		}
		return err
	}
	for _, allowed := range kinds {
		if kind == allowed {
			return nil
		}
	}
	return ErrInvalidShopData
}

func (s *Store) SaveManagedItem(it ManagedItem) (ManagedItem, error) {
	if strings.TrimSpace(it.Code) == "" || len(it.Code) > 80 || strings.TrimSpace(it.Name) == "" || len([]rune(it.Name)) > 100 || len([]rune(it.Description)) > 2000 {
		return it, ErrInvalidShopData
	}
	tx, err := s.db.Begin()
	if err != nil {
		return it, err
	}
	defer func() { _ = tx.Rollback() }()
	for _, id := range []string{it.CoverAsset, it.ActiveAsset, it.ExpiredAsset} {
		if err = requireAsset(tx, id, "svg"); err != nil {
			return it, err
		}
	}
	if err = requireAsset(tx, it.AnimationAsset, "svg", "lottie"); err != nil {
		return it, err
	}
	now := fmtTime(time.Now())
	if it.ID == 0 {
		err = tx.QueryRow(`INSERT INTO items(code,name,description,cover_asset,active_asset,expired_asset,animation_asset,created_at,updated_at) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$8) RETURNING id`, it.Code, it.Name, it.Description, it.CoverAsset, it.ActiveAsset, it.ExpiredAsset, it.AnimationAsset, now).Scan(&it.ID)
	} else {
		res, e := tx.Exec(`UPDATE items SET name=$2,description=$3,cover_asset=$4,active_asset=$5,expired_asset=$6,animation_asset=$7,updated_at=$8 WHERE id=$1 AND code=$9`, it.ID, it.Name, it.Description, it.CoverAsset, it.ActiveAsset, it.ExpiredAsset, it.AnimationAsset, now, it.Code)
		err = e
		if err == nil {
			n, _ := res.RowsAffected()
			if n != 1 {
				err = ErrInvalidShopData
			}
		}
	}
	if isUniqueViolation(err) {
		return it, fmt.Errorf("%w: item code already exists", ErrInvalidShopData)
	}
	if err != nil {
		return it, err
	}
	if it.Effect != nil {
		var existingKind string
		if err = tx.QueryRow(`SELECT kind FROM items WHERE id=$1 FOR UPDATE`, it.ID).Scan(&existingKind); err != nil {
			return it, err
		}
		if existingKind != "" && existingKind != "grant_points" && existingKind != "grant_item" {
			return it, fmt.Errorf("%w: item effect is managed by another handler", ErrInvalidShopData)
		}
		effect := *it.Effect
		switch effect.Kind {
		case "none":
			effect = EventAction{}
		case "grant_points":
			if effect.Points < 1 || effect.Points > 1000000000000 {
				return it, ErrInvalidShopData
			}
			effect = EventAction{Kind: "grant_points", Points: effect.Points}
		case "grant_item":
			if effect.ItemID < 1 || effect.Quantity < 1 || effect.Quantity > 1000000 {
				return it, ErrInvalidShopData
			}
			var targetID int64
			if err = tx.QueryRow(`SELECT id FROM items WHERE id=$1 AND status='active'`, effect.ItemID).Scan(&targetID); err != nil {
				return it, ErrInvalidShopData
			}
			effect = EventAction{Kind: "grant_item", ItemID: effect.ItemID, Quantity: effect.Quantity}
		default:
			return it, ErrInvalidShopData
		}
		params, marshalErr := json.Marshal(effect)
		if marshalErr != nil {
			return it, marshalErr
		}
		if _, err = tx.Exec(`UPDATE items SET kind=$2,params_json=$3 WHERE id=$1`, it.ID, effect.Kind, string(params)); err != nil {
			return it, err
		}
		if effect.Kind == "" {
			it.Effect = nil
		} else {
			it.Effect = &effect
		}
	}
	return it, tx.Commit()
}

type ShopProduct struct {
	ID          int64  `json:"id"`
	Kind        string `json:"kind"`
	ItemID      *int64 `json:"item_id"`
	IconAsset   string `json:"icon_asset"`
	Name        string `json:"name"`
	Description string `json:"description"`
	Price       int64  `json:"price,string"`
	Status      string `json:"status"`
	SortOrder   int    `json:"sort_order"`
}

const productColumns = `p.id,p.kind,p.item_id,CASE WHEN p.kind='item' THEN i.cover_asset ELSE p.icon_asset END,
CASE WHEN p.kind='item' THEN i.name ELSE p.name END,CASE WHEN p.kind='item' THEN i.description ELSE p.description END,p.price,p.status,p.sort_order`

func (s *Store) ListShopProducts(publishedOnly bool) ([]ShopProduct, error) {
	where := ""
	if publishedOnly {
		where = ` WHERE p.status='published' AND (p.kind='custom' OR i.status='active')`
	}
	rows, err := s.db.Query(`SELECT ` + productColumns + ` FROM points_shop_products p LEFT JOIN items i ON i.id=p.item_id` + where + ` ORDER BY p.sort_order,p.id DESC`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	products := make([]ShopProduct, 0)
	for rows.Next() {
		var p ShopProduct
		if err := rows.Scan(&p.ID, &p.Kind, &p.ItemID, &p.IconAsset, &p.Name, &p.Description, &p.Price, &p.Status, &p.SortOrder); err != nil {
			return nil, err
		}
		products = append(products, p)
	}
	return products, rows.Err()
}

func (s *Store) SaveShopProduct(p ShopProduct) (ShopProduct, error) {
	if p.Price < 1 || p.Price > 1000000000000 || (p.Status != "draft" && p.Status != "published") || p.SortOrder < -1000000 || p.SortOrder > 1000000 {
		return p, ErrInvalidShopData
	}
	tx, err := s.db.Begin()
	if err != nil {
		return p, err
	}
	defer func() { _ = tx.Rollback() }()
	switch p.Kind {
	case "item":
		if p.ItemID == nil {
			return p, ErrInvalidShopData
		}
		var active, expired, animation, state string
		err = tx.QueryRow(`SELECT name,description,cover_asset,active_asset,expired_asset,animation_asset,status FROM items WHERE id=$1 FOR SHARE`, *p.ItemID).Scan(&p.Name, &p.Description, &p.IconAsset, &active, &expired, &animation, &state)
		if errors.Is(err, sql.ErrNoRows) {
			return p, ErrInvalidShopData
		}
		if err != nil {
			return p, err
		}
		if state != "active" {
			return p, ErrInvalidShopData
		}
		for _, id := range []string{p.IconAsset, active, expired} {
			if err = requireAsset(tx, id, "svg"); err != nil {
				return p, err
			}
		}
		if err = requireAsset(tx, animation, "svg", "lottie"); err != nil {
			return p, err
		}
	case "custom":
		if p.ItemID != nil || strings.TrimSpace(p.Name) == "" || len([]rune(p.Name)) > 100 || strings.TrimSpace(p.Description) == "" || len([]rune(p.Description)) > 2000 {
			return p, ErrInvalidShopData
		}
		if err = requireAsset(tx, p.IconAsset, "svg", "image"); err != nil {
			return p, err
		}
	default:
		return p, ErrInvalidShopData
	}
	now := fmtTime(time.Now())
	if p.ID == 0 {
		err = tx.QueryRow(`INSERT INTO points_shop_products(kind,item_id,icon_asset,name,description,price,status,sort_order,created_at,updated_at) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$9,$9) RETURNING id`, p.Kind, p.ItemID, p.IconAsset, p.Name, p.Description, p.Price, p.Status, p.SortOrder, now).Scan(&p.ID)
	} else {
		res, e := tx.Exec(`UPDATE points_shop_products SET kind=$2,item_id=$3,icon_asset=$4,name=$5,description=$6,price=$7,status=$8,sort_order=$9,updated_at=$10 WHERE id=$1`, p.ID, p.Kind, p.ItemID, p.IconAsset, p.Name, p.Description, p.Price, p.Status, p.SortOrder, now)
		err = e
		if err == nil {
			n, _ := res.RowsAffected()
			if n != 1 {
				err = sql.ErrNoRows
			}
		}
	}
	if err != nil {
		return p, err
	}
	return p, tx.Commit()
}

func (s *Store) SetShopProductStatus(id int64, status string) error {
	if status != "draft" && status != "published" {
		return ErrInvalidShopData
	}
	// Update only status; publishing must not overwrite a concurrent price edit.
	var updated int64
	return s.db.QueryRow(`UPDATE points_shop_products p SET status=$2,updated_at=$3 WHERE p.id=$1
	 AND ($2='draft' OR p.kind='custom' OR EXISTS(SELECT 1 FROM items i WHERE i.id=p.item_id AND i.status='active'
	 AND i.cover_asset<>'' AND i.active_asset<>'' AND i.expired_asset<>'' AND i.animation_asset<>'')) RETURNING p.id`, id, status, fmtTime(time.Now())).Scan(&updated)
}
