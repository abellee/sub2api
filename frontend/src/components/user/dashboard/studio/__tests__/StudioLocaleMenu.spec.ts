import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { mount } from '@vue/test-utils'
import { ref } from 'vue'
import StudioLocaleMenu from '../StudioLocaleMenu.vue'
const currentLocale = ref('zh')
vi.mock('vue-i18n', () => ({ useI18n: () => ({ locale: currentLocale }) }))
vi.mock('@/i18n', () => ({ availableLocales: [{ code: 'zh', name: '中文' }, { code: 'en', name: 'English' }], setLocale: vi.fn() }))
beforeEach(() => { vi.useFakeTimers(); currentLocale.value = 'zh' })
afterEach(() => vi.useRealTimers())
describe('StudioLocaleMenu', () => {
  it('closes immediately on collapse instead of repositioning the open menu', async () => {
    const wrapper = mount(StudioLocaleMenu, { props: { expanded: true } })
    await wrapper.find('button').trigger('click')
    expect(wrapper.find('.locale-options').exists()).toBe(true)
    expect(wrapper.findComponent({ name: 'StudioPopover' }).props('side')).toBe('right')
    await wrapper.trigger('mouseleave')
    await wrapper.setProps({ expanded: false })
    expect(wrapper.find('.locale-options').exists()).toBe(false)
    await vi.advanceTimersByTimeAsync(200)
    expect(wrapper.find('.locale-options').exists()).toBe(false)
    wrapper.unmount()
  })
  it('uses the current language flag in the trigger and flags beside language options', async () => {
    const wrapper = mount(StudioLocaleMenu)
    expect(wrapper.find('.locale-trigger img').attributes('src')).toContain('flag-zh.svg')
    currentLocale.value = 'en'
    await wrapper.vm.$nextTick()
    expect(wrapper.find('.locale-trigger img').attributes('src')).toContain('flag-en.svg')
    await wrapper.find('button').trigger('click')
    expect(wrapper.findAll('.locale-options .locale-flag')).toHaveLength(2)
    wrapper.unmount()
  })
  it('opens on mouse hover, stays open across the gap and closes after leaving', async () => {
    window.matchMedia = vi.fn().mockReturnValue({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() })
    const wrapper = mount(StudioLocaleMenu)
    await wrapper.find('button').trigger('mouseenter')
    expect(wrapper.find('.locale-options').exists()).toBe(true)
    expect(wrapper.emitted('opened')).toHaveLength(1)
    await wrapper.trigger('mouseleave')
    await vi.advanceTimersByTimeAsync(100)
    await wrapper.find('.locale-options').trigger('mouseenter')
    await vi.advanceTimersByTimeAsync(200)
    expect(wrapper.find('.locale-options').exists()).toBe(true)
    await wrapper.trigger('mouseleave')
    await vi.advanceTimersByTimeAsync(200)
    expect(wrapper.find('.locale-options').exists()).toBe(false)
    wrapper.unmount()
  })
  it('keeps touch activation on click and closes when selecting the active language', async () => {
    window.matchMedia = vi.fn().mockReturnValue({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() })
    const wrapper = mount(StudioLocaleMenu)
    await wrapper.find('button').trigger('mouseenter')
    expect(wrapper.find('.locale-options').exists()).toBe(false)
    await wrapper.find('button').trigger('click')
    expect(wrapper.find('.locale-options').exists()).toBe(true)
    await wrapper.find('.locale-options button').trigger('click')
    expect(wrapper.find('.locale-options').exists()).toBe(false)
    wrapper.unmount()
  })
})
